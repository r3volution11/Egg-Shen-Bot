#!/usr/bin/env node
/**
 * Builds a standalone, self-contained static-file copy of the event-request
 * form for one entry in scripts/domains.json, ready to be nginx's `root`
 * for that domain. Replaces the old manual "public-dev/" copy — each
 * community this bot serves (e.g. Shudder, the bot's own test server) gets
 * its own domains/<label>/ output with its own config.js and its own
 * themed CSS, generated from one committed manifest instead of hand-copied
 * files that silently drift from public/.
 *
 * Usage:
 *   node scripts/deploy-domain-copy.js <label>
 *   node scripts/deploy-domain-copy.js --all
 *
 * Run `npm run build:web` first so public/css/themes/<theme>/ exists for
 * whichever theme(s) domains.json references.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.join(__dirname, '..');

const CONFIG_TEMPLATE = (guildId, logoUrl) => `// AUTO-GENERATED by scripts/deploy-domain-copy.js from scripts/domains.json
// — do not hand-edit; re-run the script instead.
window.EGG_SHEN_CONFIG = {
  GUILD_ID: '${guildId}',
  LOGO_URL: '${logoUrl || ''}',
};
`;

function copyRecursive(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyRecursive(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

function deployDomain(label, manifestEntry) {
  const { guildId, theme, logoUrl } = manifestEntry;
  const themeCssPath = path.join(ROOT, `public/css/themes/${theme}/bootstrap.min.css`);
  if (!fs.existsSync(themeCssPath)) {
    throw new Error(`No compiled CSS for theme "${theme}" (expected ${path.relative(ROOT, themeCssPath)}) — run \`npm run build:web\` first.`);
  }

  const outDir = path.join(ROOT, 'domains', label);
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  for (const file of ['index.html', 'app.js', 'style.css']) {
    fs.copyFileSync(path.join(ROOT, 'public', file), path.join(outDir, file));
  }
  copyRecursive(path.join(ROOT, 'public/crop'), path.join(outDir, 'crop'));
  copyRecursive(path.join(ROOT, 'public/img'), path.join(outDir, 'img'));

  fs.mkdirSync(path.join(outDir, 'css'), { recursive: true });
  fs.copyFileSync(themeCssPath, path.join(outDir, 'css/bootstrap.min.css'));

  fs.writeFileSync(path.join(outDir, 'config.js'), CONFIG_TEMPLATE(guildId, logoUrl));

  console.log(`✓ Deployed domains/${label}/ (guild ${guildId}, theme "${theme}")`);
}

export function main() {
  const args = process.argv.slice(2);
  const manifestPath = path.join(ROOT, 'scripts/domains.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

  if (args.includes('--all')) {
    for (const [label, entry] of Object.entries(manifest)) {
      deployDomain(label, entry);
    }
    return;
  }

  const label = args[0];
  if (!label) {
    console.error('Usage: node scripts/deploy-domain-copy.js <label> | --all');
    console.error(`Known labels: ${Object.keys(manifest).join(', ')}`);
    process.exit(1);
  }

  const entry = manifest[label];
  if (!entry) {
    console.error(`"${label}" isn't in scripts/domains.json. Known labels: ${Object.keys(manifest).join(', ')}`);
    process.exit(1);
  }

  deployDomain(label, entry);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
